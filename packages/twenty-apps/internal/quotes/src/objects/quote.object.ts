// Fields the app keeps up to date; editing them by hand would put the quote
// out of step with its lines or its customer's response.
const systemText = (
  universalIdentifier: string,
  name: string,
  label: string,
  icon: string,
  description: string,
) => ({
  universalIdentifier,
  type: FieldType.TEXT as const,
  name,
  label,
  icon,
  description,
  isNullable: true as const,
  isUIEditable: false as const,
});

const systemDateTime = (
  universalIdentifier: string,
  name: string,
  label: string,
  icon: string,
  description: string,
) => ({
  universalIdentifier,
  type: FieldType.DATE_TIME as const,
  name,
  label,
  icon,
  description,
  isNullable: true as const,
  isUIEditable: false as const,
});

